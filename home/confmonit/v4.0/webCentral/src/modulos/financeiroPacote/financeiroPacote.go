func pacotePage(w http.ResponseWriter, r *http.Request) {
	templ := []string{
		"public/templates/financeiroPacote/financeiroPacote.html",
		"public/templates/components/pagina.html",
		"public/templates/components/navbar.html",
		"public/templates/components/tabela.html",
	}

	page, err := template.ParseFiles(templ...)
	if err != nil {
		fmt.Println(err)
	}

	var d = tipos.Page{
		Titulo:       "Pacote",
		NavbarLink:   "/financeiro",
		NavbarIcon:   "bi bi-box-seam",
		NavbarTitulo: "Pacote",
	}
	if err := page.ExecuteTemplate(w, "financeiroPacote.html", d); err != nil {
		fmt.Println(err)
	}

}

